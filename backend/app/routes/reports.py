"""NexusAI Talent OS — Reports Routes"""
from fastapi import APIRouter, Depends, HTTPException, Request
from fastapi.responses import PlainTextResponse
from sqlalchemy import select
from sqlalchemy.orm import selectinload
from sqlalchemy.ext.asyncio import AsyncSession
from app.core.database import get_db
from app.models.models import Evaluation, Interview, Answer, Candidate, Job

router = APIRouter()

@router.get("/{interview_id}")
async def get_report(interview_id: str, request: Request, db: AsyncSession = Depends(get_db)):
    org_id = getattr(request.state, "org_id", None)
    ev = await db.scalar(
        select(Evaluation).options(selectinload(Evaluation.answer_evaluations))
        .where(Evaluation.interview_id == interview_id)
    )
    if not ev: raise HTTPException(404, "Report not found — evaluation may still be processing")
    iv = await db.get(Interview, interview_id)
    cand = await db.get(Candidate, iv.candidate_id) if iv else None
    job = await db.get(Job, iv.job_id) if iv else None
    from app.models.models import ProctoringEvent
    p_count = await db.scalar(
        select(__import__("sqlalchemy", fromlist=["func"]).func.count())
        .where(ProctoringEvent.interview_id == interview_id)
    ) or 0
    return {
        "evaluation": ev.__dict__,
        "candidate": {"full_name": cand.full_name, "email": cand.email} if cand else {},
        "job_title": job.title if job else "",
        "application_status": "evaluated",
        "proctoring_summary": {
            "total_events": p_count,
            "risk_score": iv.proctoring_risk_score if iv else 0,
            "risk_level": "low" if (iv and iv.proctoring_risk_score < 0.3) else
                          "medium" if (iv and iv.proctoring_risk_score < 0.6) else "high",
            "integrity_score": max(0, 100 - int((iv.proctoring_risk_score if iv else 0) * 100)),
        },
    }

@router.get("/{interview_id}/text", response_class=PlainTextResponse)
async def get_report_text(interview_id: str, db: AsyncSession = Depends(get_db)):
    ev = await db.scalar(
        select(Evaluation).options(selectinload(Evaluation.answer_evaluations))
        .where(Evaluation.interview_id == interview_id)
    )
    if not ev: raise HTTPException(404)
    iv = await db.get(Interview, interview_id)
    cand = await db.get(Candidate, iv.candidate_id) if iv else None
    job = await db.get(Job, iv.job_id) if iv else None
    answers = (await db.scalars(select(Answer).where(Answer.interview_id == interview_id).order_by(Answer.created_at))).all()
    lines = [
        "=" * 65, "NexusAI Talent OS — Interview Evaluation Report",
        "=" * 65,
        f"Candidate:      {cand.full_name if cand else 'N/A'}",
        f"Email:          {cand.email if cand else 'N/A'}",
        f"Position:       {job.title if job else 'N/A'}",
        f"Overall Score:  {ev.overall_score:.0f}/100",
        f"Rating:         {ev.overall_rating}",
        f"Recommendation: {ev.recommendation}", "",
        "EXECUTIVE SUMMARY", "-" * 40,
        ev.executive_summary or "N/A", "",
        "TRANSCRIPT & EVALUATION", "-" * 40,
    ]
    for i, ans in enumerate(answers, 1):
        ae = next((a for a in ev.answer_evaluations if a.answer_id == ans.id), None)
        lines += [f"\nQ{i} [{ans.round_type.upper()}]: {ans.question_text}",
                  f"Answer: {ans.answer_text}",
                  f"Score: {ae.total_score:.0f}/100  |  Rating: {ae.rating}" if ae else "Not evaluated",
                  f"Feedback: {ae.candidate_feedback}" if ae else ""]
    lines += ["", "=" * 65, "Generated by NexusAI Talent OS"]
    return "\n".join(lines)
